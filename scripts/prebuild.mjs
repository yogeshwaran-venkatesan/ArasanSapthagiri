// Runs before `ng build` / `ng serve` (npm "prebuild" / "prestart").
//
// Works out the public site URL and writes everything that depends on it:
//   - src/app/core/site-url.ts   (canonical URLs, Open Graph, JSON-LD)
//   - public/sitemap.xml         (every page in app.routes.ts)
//   - public/robots.txt
//
// URL priority: SITE_URL env var → Vercel production domain → default below.
// On Vercel nothing needs configuring; add SITE_URL once a custom domain is live.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const DEFAULT_URL = 'https://hotelarasansapthagiri.com';

const fromVercel = process.env.VERCEL_PROJECT_PRODUCTION_URL;
const siteUrl = (process.env.SITE_URL || (fromVercel ? `https://${fromVercel}` : DEFAULT_URL)).replace(/\/+$/, '');

if (!/^https?:\/\/[^/\s]+$/.test(siteUrl)) {
  console.error(`prebuild: invalid site URL "${siteUrl}" (expected e.g. https://example.com)`);
  process.exit(1);
}

const write = (path, content) => {
  const file = root + path;
  let current = '';
  try { current = readFileSync(file, 'utf8'); } catch { /* new file */ }
  if (current !== content) writeFileSync(file, content);
};

write(
  'src/app/core/site-url.ts',
  `// Generated by scripts/prebuild.mjs — do not edit by hand.\n` +
    `/** Public URL of the site, used for canonical links, Open Graph and structured data. */\n` +
    `export const SITE_URL = '${siteUrl}';\n`,
);

// Page paths come straight from the router config, so the sitemap never drifts.
const routes = readFileSync(root + 'src/app/app.routes.ts', 'utf8');
const paths = ['', ...[...routes.matchAll(/path: '([a-z0-9-]+)'/g)].map((m) => m[1]).filter((p) => p !== '404')];
const priority = (p) => (p === '' ? '1.0' : ['rooms', 'book'].includes(p) ? '0.9' : '0.7');

write(
  'public/sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    paths.map((p) => `  <url><loc>${siteUrl}/${p}</loc><priority>${priority(p)}</priority></url>`).join('\n') +
    `\n</urlset>\n`,
);

write('public/robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`);

console.log(`prebuild: site URL ${siteUrl} · ${paths.length} pages in sitemap`);
